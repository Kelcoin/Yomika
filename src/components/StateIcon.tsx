export type StateIconName = keyof typeof icons;

/** Selection belongs to the owning control, not hover, focus or icon colour. */
export function StateIcon({ name, selected = false, className, ...props }: SVGProps<SVGSVGElement> & { name: StateIconName; selected?: boolean | undefined }) {
  const { outline: Outline, filled } = icons[name];
  if (!selected) return <Outline className={`app-icon${className ? ` ${className}` : ''}`} strokeWidth="1.75" aria-hidden="true" focusable="false" data-icon={name} data-icon-state="outline" {...props} />;
  return <SvgIcon className={className} data-icon={name} data-icon-state="filled" {...props}><path d={filled} fill="currentColor" fillRule="evenodd" stroke="none" /></SvgIcon>;
}
